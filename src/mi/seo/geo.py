"""SEO/AEO/GEO audit: frozen prompt panel, answer-log validation and the worksheet's metrics.

The TEAM collects real answers in data/seo/answer_log.csv (template generated by `init`). This code
never invents answers. Metrics follow the course worksheet (Step 4) with explicit denominators:
  mention rate = answers mentioning brand / answers logged (target 20)
  recommendation rate, primary-pick rate likewise
  share of voice = brand appearances / all brand appearances  (count rule: one appearance per brand per answer)
  share of recommendations = brand recommendations / all recommendations
Source gap (Step 5A): domains cited in answers where a competitor was recommended and the brand was not.
Usage: python -m mi.seo.geo init | analyze [--log path]
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter
from urllib.parse import urlparse

from mi.paths import REPORTS, SEO

PANEL = SEO / "prompt_panel.json"
LOG = SEO / "answer_log.csv"
COLUMNS = ["prompt_id", "intent", "language", "assistant", "assistant_version", "country_setting", "timestamp_utc",
           "raw_answer_sha256", "brand_mentioned", "brand_recommended", "brand_top_pick", "competitors_named",
           "competitors_recommended", "cited_urls", "source_quality_notes", "refusal_or_variability", "collected_by"]
YES = {"y", "yes", "1", "true"}


def load_panel(path=PANEL) -> dict:
    p = json.loads(open(path, encoding="utf-8").read())
    n = Counter(x["intent"] for x in p["prompts"])
    assert len(p["prompts"]) == 10 and n == {"Learn": 4, "Browse": 3, "Buy": 3}, f"panel must be 4/3/3, got {n}"
    brand = p["audited_brand"].lower()
    named = [x["id"] for x in p["prompts"] if brand in x["text"].lower()]
    assert len(named) <= 1, f"brand named in more than one prompt: {named}"
    assert sum(1 for x in p["prompts"] if x["lang"] != "en") >= 2, "need >= 2 prompts in a second language"
    return p


def init_template(path=LOG) -> str:
    p = load_panel()
    if path.exists():
        return f"{path} exists — not overwritten"
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, COLUMNS)
        w.writeheader()
        for q in p["prompts"]:
            for a in ("ASSISTANT_1", "ASSISTANT_2"):
                w.writerow({"prompt_id": q["id"], "intent": q["intent"], "language": q["lang"], "assistant": a})
    return f"template with 20 empty rows -> {path}"


def read_log(path=LOG) -> list[dict]:
    if not path.exists():
        return []
    with open(path, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return [r for r in rows if (r.get("timestamp_utc") or "").strip() and (r.get("raw_answer_sha256") or "").strip()]


def domains(urls: str) -> list[str]:
    out = []
    for u in (urls or "").replace(";", " ").split():
        d = urlparse(u if "://" in u else "https://" + u).netloc.lower().removeprefix("www.")
        if d:
            out.append(d)
    return out


def split_names(s: str) -> list[str]:
    return [x.strip() for x in (s or "").replace(";", ",").split(",") if x.strip()]


def analyze(rows: list[dict], panel: dict) -> dict:
    brand = panel["audited_brand"]
    n = len(rows)
    target = 20
    res = {"status": "OBSERVED answer log" if n else "PENDING — 0 real answers collected", "answers_logged": n,
           "answers_target": target, "brand": brand, "competitors": panel["competitors"]}
    if n == 0:
        res["note"] = "Run the frozen panel in two assistants and fill data/seo/answer_log.csv. No metric is computed from zero answers."
        return res
    yes = lambda r, k: (r.get(k) or "").strip().lower() in YES
    m = sum(yes(r, "brand_mentioned") for r in rows)
    rec = sum(yes(r, "brand_recommended") for r in rows)
    top = sum(yes(r, "brand_top_pick") for r in rows)
    appearances = Counter()
    recs = Counter()
    for r in rows:
        names = {x.lower() for x in split_names(r["competitors_named"])}
        if yes(r, "brand_mentioned"):
            names.add(brand.lower())
        appearances.update(names)  # count rule: one appearance per brand per answer
        rn = {x.lower() for x in split_names(r.get("competitors_recommended"))}
        if yes(r, "brand_recommended"):
            rn.add(brand.lower())
        recs.update(rn)
    gap = Counter()
    for r in rows:
        if split_names(r.get("competitors_recommended")) and not yes(r, "brand_recommended"):
            gap.update(set(domains(r["cited_urls"])))
    by_intent = {}
    for intent in ("Learn", "Browse", "Buy"):
        rr = [r for r in rows if r["intent"] == intent]
        by_intent[intent] = {"n": len(rr), "mentioned": sum(yes(r, "brand_mentioned") for r in rr),
                             "recommended": sum(yes(r, "brand_recommended") for r in rr)}
    funnel = {"mention": m / n, "recommend_given_mention": (rec / m) if m else None, "top_given_recommend": (top / rec) if rec else None}
    leak = min([(k, v) for k, v in funnel.items() if v is not None], key=lambda kv: kv[1])[0] if any(v is not None for v in funnel.values()) else None
    res.update({
        "mention_rate": {"value": m / n, "num": m, "den": n},
        "recommendation_rate": {"value": rec / n, "num": rec, "den": n},
        "primary_pick_rate": {"value": top / n, "num": top, "den": n},
        "share_of_voice": {"value": appearances[brand.lower()] / max(1, sum(appearances.values())),
                           "num": appearances[brand.lower()], "den": sum(appearances.values())},
        "share_of_recommendations": {"value": recs[brand.lower()] / max(1, sum(recs.values())),
                                     "num": recs[brand.lower()], "den": sum(recs.values())},
        "brand_appearances": dict(appearances), "funnel": funnel, "largest_leak": leak, "by_intent": by_intent,
        "source_gap_top3": gap.most_common(3),
        "assistants": sorted({r["assistant"] for r in rows}),
        "candidate_actions": candidate_actions(gap, by_intent, leak),
        "caveat": "Assistant answers vary by run, version and settings; these are observations of specific answers, not search ranking, traffic or sales."})
    if n < target:
        res["status"] = f"PARTIAL — {n}/{target} answers logged"
    return res


def candidate_actions(gap: Counter, by_intent: dict, leak) -> list[dict]:
    """Proposes actions FROM log evidence; impact/effort must be scored by the team (worksheet Step 5B)."""
    acts = []
    for d, c in gap.most_common(3):
        acts.append({"action": f"Earn accurate, sourced coverage on {d} (reviews / listings / comparison)",
                     "evidence": f"cited in {c} answers where a competitor was recommended and the brand was not",
                     "impact": None, "effort": None})
    weakest = min(by_intent.items(), key=lambda kv: (kv[1]["mentioned"] / kv[1]["n"]) if kv[1]["n"] else 1)[0]
    acts.append({"action": f"Publish a factual FAQ/comparison page for {weakest}-intent questions (how digital coupons work, limits, categories)",
                 "evidence": f"lowest mention rate in {weakest} prompts", "impact": None, "effort": None})
    acts.append({"action": "Keep one consistent brand/offer description and Organization/Product markup that matches visible content",
                 "evidence": f"largest funnel leak: {leak}", "impact": None, "effort": None})
    return acts[:3] + acts[3:]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["init", "analyze"])
    ap.add_argument("--log", default=str(LOG))
    a = ap.parse_args(argv)
    if a.cmd == "init":
        print(init_template())
        return 0
    from pathlib import Path
    res = analyze(read_log(Path(a.log)), load_panel())
    (REPORTS / "seo_geo_audit.json").write_text(json.dumps(res, indent=2, ensure_ascii=False))
    print(json.dumps({k: v for k, v in res.items() if k not in ("candidate_actions",)}, indent=1, ensure_ascii=False)[:2500])
    return 0


if __name__ == "__main__":
    sys.exit(main())
