"""SEO/AEO/GEO audit: frozen prompt panel, answer-log validation and the worksheet's metrics.

The TEAM collects real answers in data/seo/answer_log.csv (template generated by `init`). This code
never invents answers. Metrics follow the course worksheet (Step 4) with explicit denominators:
  mention rate = answers mentioning brand / answers logged (target 20)
  recommendation rate, primary-pick rate likewise
  share of voice = brand appearances / all brand appearances  (count rule: one appearance per brand per answer)
  share of recommendations = brand recommendations / all recommendations
Source gap (Step 5A): domains cited in answers where a competitor was recommended and the brand was not.
Usage: python -m mi.seo.geo init | freeze [--by NAME] | check | analyze [--log path]
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import Counter
from datetime import datetime, timezone
from urllib.parse import urlparse

from mi.paths import REPORTS, SEO

PANEL = SEO / "prompt_panel.json"
LOG = SEO / "answer_log.csv"
COLUMNS = ["prompt_id", "intent", "language", "assistant", "assistant_version", "country_setting", "timestamp_utc",
           "raw_answer_sha256", "brand_mentioned", "brand_recommended", "brand_top_pick", "competitors_named",
           "competitors_recommended", "cited_urls", "source_quality_notes", "refusal_or_variability", "collected_by"]
YES = {"y", "yes", "1", "true"}


def load_panel(path=PANEL) -> dict:
    p = json.loads(open(path, encoding="utf-8").read())
    n = Counter(x["intent"] for x in p["prompts"])
    assert len(p["prompts"]) == 10 and n == {"Learn": 4, "Browse": 3, "Buy": 3}, f"panel must be 4/3/3, got {n}"
    brand = p["audited_brand"].lower()
    named = [x["id"] for x in p["prompts"] if brand in x["text"].lower()]
    assert len(named) <= 1, f"brand named in more than one prompt: {named}"
    assert sum(1 for x in p["prompts"] if x["lang"] != "en") >= 2, "need >= 2 prompts in a second language"
    return p


def init_template(path=LOG) -> str:
    p = load_panel()
    if path.exists():
        return f"{path} exists — not overwritten"
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, COLUMNS)
        w.writeheader()
        for q in p["prompts"]:
            for a in ("ASSISTANT_1", "ASSISTANT_2"):
                w.writerow({"prompt_id": q["id"], "intent": q["intent"], "language": q["lang"], "assistant": a})
    return f"template with 20 empty rows -> {path}"


def read_log(path=LOG) -> list[dict]:
    if not path.exists():
        return []
    with open(path, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return [r for r in rows if (r.get("timestamp_utc") or "").strip() and (r.get("raw_answer_sha256") or "").strip()]


def domains(urls: str) -> list[str]:
    out = []
    for u in (urls or "").replace(";", " ").split():
        d = urlparse(u if "://" in u else "https://" + u).netloc.lower().removeprefix("www.")
        if d:
            out.append(d)
    return out


def split_names(s: str) -> list[str]:
    return [x.strip() for x in (s or "").replace(";", ",").split(",") if x.strip()]


def analyze(rows: list[dict], panel: dict) -> dict:
    brand = panel["audited_brand"]
    n = len(rows)
    target = 20
    res = {"status": "OBSERVED answer log" if n else "PENDING — 0 real answers collected", "answers_logged": n,
           "answers_target": target, "brand": brand, "competitors": panel["competitors"]}
    if n == 0:
        res["note"] = "Run the frozen panel in two assistants and fill data/seo/answer_log.csv. No metric is computed from zero answers."
        return res
    yes = lambda r, k: (r.get(k) or "").strip().lower() in YES
    m = sum(yes(r, "brand_mentioned") for r in rows)
    rec = sum(yes(r, "brand_recommended") for r in rows)
    top = sum(yes(r, "brand_top_pick") for r in rows)
    appearances = Counter()
    recs = Counter()
    for r in rows:
        names = {x.lower() for x in split_names(r["competitors_named"])}
        if yes(r, "brand_mentioned"):
            names.add(brand.lower())
        appearances.update(names)  # count rule: one appearance per brand per answer
        rn = {x.lower() for x in split_names(r.get("competitors_recommended"))}
        if yes(r, "brand_recommended"):
            rn.add(brand.lower())
        recs.update(rn)
    gap = Counter()
    for r in rows:
        if split_names(r.get("competitors_recommended")) and not yes(r, "brand_recommended"):
            gap.update(set(domains(r["cited_urls"])))
    by_intent = {}
    for intent in ("Learn", "Browse", "Buy"):
        rr = [r for r in rows if r["intent"] == intent]
        by_intent[intent] = {"n": len(rr), "mentioned": sum(yes(r, "brand_mentioned") for r in rr),
                             "recommended": sum(yes(r, "brand_recommended") for r in rr)}
    funnel = {"mention": m / n, "recommend_given_mention": (rec / m) if m else None, "top_given_recommend": (top / rec) if rec else None}
    leak = min([(k, v) for k, v in funnel.items() if v is not None], key=lambda kv: kv[1])[0] if any(v is not None for v in funnel.values()) else None
    res.update({
        "mention_rate": {"value": m / n, "num": m, "den": n},
        "recommendation_rate": {"value": rec / n, "num": rec, "den": n},
        "primary_pick_rate": {"value": top / n, "num": top, "den": n},
        "share_of_voice": {"value": appearances[brand.lower()] / max(1, sum(appearances.values())),
                           "num": appearances[brand.lower()], "den": sum(appearances.values())},
        "share_of_recommendations": {"value": recs[brand.lower()] / max(1, sum(recs.values())),
                                     "num": recs[brand.lower()], "den": sum(recs.values())},
        "brand_appearances": dict(appearances), "funnel": funnel, "largest_leak": leak, "by_intent": by_intent,
        "source_gap_top3": gap.most_common(3),
        "assistants": sorted({r["assistant"] for r in rows}),
        "candidate_actions": candidate_actions(gap, by_intent, leak),
        "caveat": "Assistant answers vary by run, version and settings; these are observations of specific answers, not search ranking, traffic or sales."})
    if n < target:
        res["status"] = f"PARTIAL — {n}/{target} answers logged"
    return res


def candidate_actions(gap: Counter, by_intent: dict, leak) -> list[dict]:
    """Proposes actions FROM log evidence; impact/effort must be scored by the team (worksheet Step 5B)."""
    acts = []
    for d, c in gap.most_common(3):
        acts.append({"action": f"Earn accurate, sourced coverage on {d} (reviews / listings / comparison)",
                     "evidence": f"cited in {c} answers where a competitor was recommended and the brand was not",
                     "impact": None, "effort": None})
    weakest = min(by_intent.items(), key=lambda kv: (kv[1]["mentioned"] / kv[1]["n"]) if kv[1]["n"] else 1)[0]
    acts.append({"action": f"Publish a factual FAQ/comparison page for {weakest}-intent questions (how digital coupons work, limits, categories)",
                 "evidence": f"lowest mention rate in {weakest} prompts", "impact": None, "effort": None})
    acts.append({"action": "Keep one consistent brand/offer description and Organization/Product markup that matches visible content",
                 "evidence": f"largest funnel leak: {leak}", "impact": None, "effort": None})
    return acts[:3] + acts[3:]


REQUIRED = ["assistant_version", "country_setting", "timestamp_utc", "raw_answer_sha256", "brand_mentioned",
            "brand_recommended", "brand_top_pick", "collected_by"]


def panel_sha16(panel: dict) -> str:
    import hashlib
    return hashlib.sha256(json.dumps(panel["prompts"], sort_keys=True, ensure_ascii=False).encode()).hexdigest()[:16]


def check(log_path=LOG, panel_path=PANEL) -> dict:
    """Collection checklist: which of the 20 rows are missing or incomplete, and whether settings stayed identical."""
    panel = load_panel(panel_path)
    rows = list(csv.DictReader(open(log_path, encoding="utf-8"))) if log_path.exists() else []
    have = {(str(r.get("prompt_id")), r.get("assistant")): r for r in rows}
    missing, incomplete = [], []
    for q in panel["prompts"]:
        for a in ("ASSISTANT_1", "ASSISTANT_2"):
            r = have.get((str(q["id"]), a))
            if r is None:
                missing.append(f"P{q['id']:02d}/{a}")
                continue
            gaps = [k for k in REQUIRED if not (r.get(k) or "").strip()]
            bad_yn = [k for k in ("brand_mentioned", "brand_recommended", "brand_top_pick")
                      if (r.get(k) or "").strip() and r[k].strip().lower() not in YES | {"n", "no", "0", "false"}]
            if gaps or bad_yn:
                incomplete.append({"row": f"P{q['id']:02d}/{a}", "empty": gaps, "not_Y_or_N": bad_yn})
    settings = {}
    for r in rows:
        if (r.get("timestamp_utc") or "").strip():
            settings.setdefault(r["assistant"], set()).add(((r.get("assistant_version") or "").strip(), (r.get("country_setting") or "").strip()))
    drift = {a: sorted(map(list, s)) for a, s in settings.items() if len(s) > 1}
    frozen = panel.get("frozen", {})
    started = any((r.get("timestamp_utc") or "").strip() for r in rows)
    freeze_ok = bool(frozen) and frozen.get("prompts_sha16") == panel_sha16(panel)
    return {"complete_rows": 20 - len(missing) - len(incomplete), "target": 20, "missing_rows": missing, "incomplete_rows": incomplete,
            "settings_drift": drift, "panel_frozen": freeze_ok, "panel_sha16": panel_sha16(panel),
            "warning": (None if freeze_ok or not started else "answers logged but the panel was not frozen at this version: re-freeze is NOT allowed mid-run; restart collection")}


def geo_state(log_path=LOG, panel_path=PANEL) -> dict:
    """One read of the real GEO state, for every generator that needs it (work items, briefs, app text).

    Nothing here is typed by hand: counts come from the answer log, completeness from `check`. `complete` is True
    only when all target rows pass the collection check and the panel is frozen at the logged version.
    """
    panel = load_panel(panel_path)
    rows = read_log(log_path)
    chk = check(log_path, panel_path)
    res = analyze(rows, panel)
    n, target = res["answers_logged"], res["answers_target"]
    complete = bool(n >= target and chk["complete_rows"] >= target and chk["panel_frozen"])
    st = {"answers_logged": n, "answers_target": target, "complete_rows": chk["complete_rows"], "complete": complete,
          "brand": panel["audited_brand"], "competitors": panel["competitors"],
          "answers_remaining": max(0, target - chk["complete_rows"]),
          "assistants": sorted({(r.get("assistant_version") or "").split(" (")[0].strip() for r in rows if (r.get("assistant_version") or "").strip()}),
          "dates": sorted({(r.get("timestamp_utc") or "")[:10] for r in rows if (r.get("timestamp_utc") or "").strip()}),
          "answers_citing_urls": sum(1 for r in rows if (r.get("cited_urls") or "").strip()),
          "region_set": any(not (r.get("country_setting") or "").lower().startswith("none") for r in rows if (r.get("country_setting") or "").strip())}
    if n:
        st.update({k: res[k] for k in ("mention_rate", "recommendation_rate", "primary_pick_rate", "by_intent")})
    return st


def geo_pending_phrase(state: dict | None = None) -> str:
    """Short wording for 'what is left on GEO', for generated lists and tables (never says to collect answers that exist)."""
    s = state or geo_state()
    if not s["complete"]:
        return f"the remaining {s['answers_remaining'] or s['answers_target']} of {s['answers_target']} GEO answers"
    return "team scoring of the GEO audit and a ChatGPT/Gemini retest"


def geo_task(state: dict | None = None) -> dict:
    """The work item the advisor should queue for the CURRENT GEO state (collection task only while rows are missing)."""
    s = state or geo_state()
    if not s["complete"]:
        rem = s["answers_remaining"] or s["answers_target"]
        return {"title": f"Collect the remaining {rem} of {s['answers_target']} GEO answers",
                "draft": "docs/seo_geo_protocol.md", "success_metric": f"python -m mi.seo.geo check reports complete_rows = {s['answers_target']}",
                "decision_it_changes": "whether plan C (content) is worth doing", "advisor_note": "collection task: the answer log is incomplete",
                "phase": "COLLECT"}
    li = s["by_intent"]["Learn"]
    m, r = s["mention_rate"], s["recommendation_rate"]
    return {"title": (f"Review the completed {s['answers_target']}-answer GEO audit ({s['brand']} analogue), score impact and effort, "
                      "and plan the ChatGPT/Gemini retest"),
            "draft": "docs/geo_audit_results.md",
            "success_metric": "team scores impact and effort (1 to 3) for each candidate action; frozen panel re-run in ChatGPT and Gemini before any claim about them",
            "decision_it_changes": "whether a Learn-intent content draft (plan C) is worth writing",
            "advisor_note": (f"{s['answers_logged']}/{s['answers_target']} answers collected ({', '.join(s['assistants'])}; one dated run {', '.join(s['dates'])}; "
                             f"region {'set' if s['region_set'] else 'not set'}; {s['answers_target'] - s['answers_citing_urls']} answers made without web search (no sources cited)). "
                             f"{s['brand']} (public analogue, not the dataset retailer) mentioned {m['num']}/{m['den']}, recommended {r['num']}/{r['den']}; "
                             f"Learn: mentioned {li['mentioned']}/{li['n']}, recommended {li['recommended']}/{li['n']}. Observed AI-answer visibility only: "
                             "no traffic, conversion or sales effect is claimed; any content draft needs human approval before publication."),
            "phase": "REVIEW"}


def freeze(panel_path=PANEL, by="team") -> str:
    panel = json.loads(open(panel_path, encoding="utf-8").read())
    if any((r.get("timestamp_utc") or "").strip() for r in (csv.DictReader(open(LOG, encoding="utf-8")) if LOG.exists() else [])):
        return "refused: answers already logged; the panel must be frozen BEFORE the first assistant run"
    load_panel(panel_path)  # validates 4/3/3, brand-once, second-language rule
    panel["frozen"] = {"at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"), "by": by, "prompts_sha16": panel_sha16(panel)}
    open(panel_path, "w", encoding="utf-8").write(json.dumps(panel, indent=2, ensure_ascii=False) + "\n")
    return f"frozen {panel['frozen']}"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["init", "analyze", "check", "freeze"])
    ap.add_argument("--log", default=str(LOG))
    ap.add_argument("--by", default="team")
    a = ap.parse_args(argv)
    if a.cmd == "init":
        print(init_template())
        return 0
    if a.cmd == "check":
        from pathlib import Path
        print(json.dumps(check(Path(a.log)), indent=1, ensure_ascii=False))
        return 0
    if a.cmd == "freeze":
        print(freeze(by=a.by))
        return 0
    from pathlib import Path
    res = analyze(read_log(Path(a.log)), load_panel())
    (REPORTS / "seo_geo_audit.json").write_text(json.dumps(res, indent=2, ensure_ascii=False))
    print(json.dumps({k: v for k, v in res.items() if k not in ("candidate_actions",)}, indent=1, ensure_ascii=False)[:2500])
    return 0


if __name__ == "__main__":
    sys.exit(main())
